#!/usr/bin/env python3
"""Analyze calibration samples and compute optimal HSV boundaries.

Usage:
    python color_boundary_analysis.py --input calibration_samples.json --output boundaries.py

This tool:
    1. Loads samples from color_calibration.py
    2. Computes statistics (mean, std, min, max) per color
    3. Suggests boundary values between adjacent colors
    4. Generates Python code to update color_quant.py

The output is human-readable and reviewable before applying to production.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

try:
    import numpy as np
    NUMPY_AVAILABLE = True
except ImportError:
    NUMPY_AVAILABLE = False


@dataclass
class ColorStats:
    """Statistics for one color across all samples."""
    color_name: str
    h_mean: float
    h_std: float
    h_min: float
    h_max: float
    s_mean: float
    s_std: float
    v_mean: float
    v_std: float
    sample_count: int


def compute_color_stats(samples: list[dict[str, Any]]) -> dict[str, ColorStats]:
    """Compute statistics per color from calibration samples.

    Args:
        samples: List of ColorSample dicts from JSON.

    Returns:
        Dict mapping color_name to ColorStats.
    """
    if not NUMPY_AVAILABLE:
        raise RuntimeError("numpy is required for statistical analysis")

    # Group samples by color
    by_color = defaultdict(list)
    for sample in samples:
        by_color[sample["color_name"]].append(sample)

    stats = {}
    for color_name, color_samples in by_color.items():
        h_values = [s["h_mean"] for s in color_samples]
        s_values = [s["s_mean"] for s in color_samples]
        v_values = [s["v_mean"] for s in color_samples]

        stats[color_name] = ColorStats(
            color_name=color_name,
            h_mean=float(np.mean(h_values)),
            h_std=float(np.std(h_values)),
            h_min=float(np.min(h_values)),
            h_max=float(np.max(h_values)),
            s_mean=float(np.mean(s_values)),
            s_std=float(np.std(s_values)),
            v_mean=float(np.mean(v_values)),
            v_std=float(np.std(v_values)),
            sample_count=len(color_samples),
        )

    return stats


def suggest_hue_boundaries(stats: dict[str, ColorStats]) -> dict[str, tuple[float, float]]:
    """Suggest hue boundaries for each color.

    Args:
        stats: Color statistics.

    Returns:
        Dict mapping color_name to (lower_bound, upper_bound) in degrees.
    """
    # Sort by hue mean (handle red wrap-around: 0-360)
    sorted_colors = sorted(stats.values(), key=lambda s: s.h_mean)

    boundaries = {}
    for i, color in enumerate(sorted_colors):
        # Use mean ± 2*std as initial bounds
        lower = color.h_mean - 2 * color.h_std
        upper = color.h_mean + 2 * color.h_std

        # Adjust based on neighbors
        if i > 0:
            prev_color = sorted_colors[i - 1]
            # Midpoint between this color and previous
            midpoint = (prev_color.h_mean + color.h_mean) / 2
            lower = max(lower, midpoint)

        if i < len(sorted_colors) - 1:
            next_color = sorted_colors[i + 1]
            midpoint = (color.h_mean + next_color.h_mean) / 2
            upper = min(upper, midpoint)

        # Clamp to [0, 360]
        lower = max(0, lower)
        upper = min(360, upper)

        boundaries[color.color_name] = (lower, upper)

    return boundaries


def generate_python_code(stats: dict[str, ColorStats], boundaries: dict[str, tuple[float, float]]) -> str:
    """Generate Python code to update color_quant.py.

    Args:
        stats: Color statistics.
        boundaries: Suggested hue boundaries.

    Returns:
        Python code string.
    """
    lines = [
        "# Auto-generated by color_boundary_analysis.py",
        "# Based on on-site calibration samples",
        "",
        "# Color statistics:",
    ]

    for color_name, stat in sorted(stats.items()):
        lines.append(f"# {color_name}: H={stat.h_mean:.1f}° (±{stat.h_std:.1f}), "
                     f"S={stat.s_mean:.3f} (±{stat.s_std:.3f}), "
                     f"V={stat.v_mean:.3f} (±{stat.v_std:.3f}), "
                     f"n={stat.sample_count}")

    lines.extend([
        "",
        "# Suggested hue boundaries (degrees):",
        "HUE_BOUNDARIES = {",
    ])

    for color_name, (lower, upper) in sorted(boundaries.items()):
        lines.append(f'    "{color_name}": ({lower:.1f}, {upper:.1f}),')

    lines.extend([
        "}",
        "",
        "# Usage in color_quant.py:",
        "# Update the color_name() function to use these boundaries",
        "# Example:",
        "#   if HUE_BOUNDARIES['red'][0] <= hue_deg < HUE_BOUNDARIES['red'][1]:",
        "#       return 'red'",
    ])

    return "\n".join(lines)


def print_summary(stats: dict[str, ColorStats], boundaries: dict[str, tuple[float, float]]) -> None:
    """Print human-readable summary to console."""
    print("\n=== Color Statistics ===\n")
    print(f"{'Color':<12} {'H_mean':>8} {'H_std':>8} {'H_range':>15} {'S_mean':>8} {'V_mean':>8} {'Samples':>8}")
    print("-" * 85)

    for color_name, stat in sorted(stats.items(), key=lambda x: x[1].h_mean):
        h_range = f"[{stat.h_min:.0f}, {stat.h_max:.0f}]"
        print(f"{color_name:<12} {stat.h_mean:>8.1f} {stat.h_std:>8.1f} {h_range:>15} "
              f"{stat.s_mean:>8.3f} {stat.v_mean:>8.3f} {stat.sample_count:>8}")

    print("\n=== Suggested Hue Boundaries ===\n")
    print(f"{'Color':<12} {'Lower':>8} {'Upper':>8} {'Width':>8}")
    print("-" * 40)

    for color_name, (lower, upper) in sorted(boundaries.items(), key=lambda x: x[1][0]):
        width = upper - lower
        print(f"{color_name:<12} {lower:>8.1f} {upper:>8.1f} {width:>8.1f}")

    print("\n⚠️ Review these boundaries carefully before applying to production!")
    print("   Adjust for overlapping ranges or colors with high std.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Analyze color calibration samples")
    parser.add_argument("--input", type=Path, required=True,
                        help="Input JSON from color_calibration.py")
    parser.add_argument("--output", type=Path, default="boundaries.py",
                        help="Output Python code file")

    args = parser.parse_args(argv)

    if not NUMPY_AVAILABLE:
        print("ERROR: numpy is required for this tool", file=sys.stderr)
        print("Install: pip install numpy", file=sys.stderr)
        return 1

    if not args.input.exists():
        print(f"ERROR: Input file not found: {args.input}", file=sys.stderr)
        return 1

    # Load samples
    data = json.loads(args.input.read_text(encoding="utf-8"))
    samples = data["samples"]

    if not samples:
        print("ERROR: No samples found in input file", file=sys.stderr)
        return 1

    print(f"Loaded {len(samples)} samples from {args.input}")
    print(f"Lighting notes: {data.get('lighting_notes', 'N/A')}")

    # Compute statistics
    stats = compute_color_stats(samples)
    boundaries = suggest_hue_boundaries(stats)

    # Print summary
    print_summary(stats, boundaries)

    # Generate code
    code = generate_python_code(stats, boundaries)
    args.output.write_text(code, encoding="utf-8")

    print(f"\n✓ Python code saved to: {args.output}")
    print("\nNext steps:")
    print("  1. Review the suggested boundaries")
    print("  2. Manually update sorting_vision/color_quant.py")
    print("  3. Run validation tests with real images")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
