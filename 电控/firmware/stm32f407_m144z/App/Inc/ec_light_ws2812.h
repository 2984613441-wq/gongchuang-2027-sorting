#ifndef EC_LIGHT_WS2812_H
#define EC_LIGHT_WS2812_H

#include <stdbool.h>
#include <stdint.h>

/* 2026-10-18 新增：WS2812 补光灯驱动（软件位模拟，跑在 PC0 / LIGHT_EN）。
 *
 * ── 为什么不能用普通 GPIO 开关 ────────────────────────────────────────────
 * WS2812 是单总线 800kHz 协议：T0H≈0.4us / T1H≈0.8us / 位周期 1.25us，
 * 帧间低电平 >50us 锁存。单纯把 PC0 拉高**不会点亮**，必须按位发送 GRB 数据。
 *
 * ── 为什么用位模拟而不是 PWM+DMA ──────────────────────────────────────────
 * 本工程 main.c 目前没有任何 MX_DMA_Init（DMA 一个通道都没配）。
 * 补光灯只需要"开 / 关 / 调亮度"这种低频操作，
 * 位模拟每次占用约 0.5ms 关中断即可，
 * 改动面远小于为一个灯新引入 DMA 链路。
 *
 * ── 硬件接法（2026-10-18 用户确认）────────────────────────────────────────
 *   PC0 ──[330Ω]──► WS2812 DIN
 *   5V 电源 ──┬──► WS2812 VDD
 *             └──► 1000uF 电解电容 ── GND
 *   5V 电源 GND ══► STM32 GND（必须共地，否则信号无参考）
 *
 * ── 负载与亮度上限 ────────────────────────────────────────────────────────
 * 16 颗 × 0.3W = 4.8W ≈ 1.0A @5V（全白满载）。
 * 为不超过降压模块 5V 那路的余量，默认亮度取 50%（≈0.5A）。
 *
 * ── 已知限制 ──────────────────────────────────────────────────────────────
 * 发送一帧 48 字节需要 ≈480us，这段时间 __disable_irq() 关闭中断。
 * USART2 在 115200 下 480us ≈ 5.5 个字节时间，理论上可能丢字节；
 * 但补光灯只在开/关时更新，且本函数不参与协议路径，实测风险可接受。
 * 若将来需要高频刷新，应改为 PWM+DMA 方案。
 */

#define EC_WS2812_LED_COUNT 16U
#define EC_WS2812_BYTES (EC_WS2812_LED_COUNT * 3U)

#define EC_WS2812_LEVEL_MAX 255U
#define EC_WS2812_DEFAULT_LEVEL 255U

/* ── 白光通道校正（2026-10-18 实测定标）──────────────────────────────────
 * WS2812 三色 LED 的发光效率并不相等：红光最弱、蓝光最强。
 * 直接写 R=G=B 会打出严重偏蓝的白（实测白纸饱和度 45.9%，蓝比红高 85%），
 * 这会让 HSV 六色窗口判据整体错位 —— 白托盘在画面里会变成"蓝色物体"。
 *
 * 在实物上扫描了 6 组值并测白纸饱和度：
 *   (180,180,180) → S=45.92%   偏色重
 *   (222,183,120) → S=16.14%   仍偏蓝
 *   (255,210,138) → S=16.84%   仍偏蓝
 *   (255,200, 90) → S= 2.20%   ★ 选中（关灯基准 1.07%）
 *   (255,180, 70) → S= 3.41%
 *   (255,160, 60) → S= 6.11%
 *
 * ⇒ 白光 = (255, 200, 90)。实测输出白纸 RGB=(176.2,172.3,176.2)，三通道基本相等。
 * 该比例下 16 颗总功率约 3.4W（≈0.68A @5V），低于满载 4.8W(1.0A)。
 * 若更换灯珠批次，必须重新扫这组值。 */
#define EC_WS2812_WHITE_R 255U
#define EC_WS2812_WHITE_G 200U
#define EC_WS2812_WHITE_B 90U

/* 使能 DWT 周期计数器并把数据线拉低。可重复调用。 */
void ec_ws2812_init(void);

/* 发送调用者提供的 GRB 数组（长度 = 灯珠数 × 3）。 */
void ec_ws2812_send_grb(const uint8_t *grb, uint16_t len);

/* 所有灯珠设为同一颜色 / 熄灭。 */
void ec_ws2812_fill(uint8_t r, uint8_t g, uint8_t b);
void ec_ws2812_off(void);

/* 按当前记录的亮度点亮白光；set_white_level 会立即生效。 */
void ec_ws2812_white_on(void);
bool ec_ws2812_set_white_level(uint8_t level);
uint8_t ec_ws2812_white_level(void);

#endif /* EC_LIGHT_WS2812_H */
